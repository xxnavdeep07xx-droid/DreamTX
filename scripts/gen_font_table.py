#!/usr/bin/env python3
"""Generate deck-core's static font advance-width table (font_metrics.rs)
from the four bundled DejaVu TTFs.

Replaces the embedded 2.16 MB of `include_bytes!` fonts + the ttf-parser
dependency: the layout solver only ever needs `units_per_em` and
`glyph_hor_advance(gid)` for every cmap-mapped codepoint, so a pre-generated
sorted (codepoint, advance) table per face gives bit-identical `measure()`
and `wrap()` results at ~6 bytes per glyph.

Regeneration (the .rs is committed; this script exists for provenance):
    python3 scripts/gen_font_table.py core/crates/deck-core/fonts \
        > core/crates/deck-core/src/font_metrics.rs
Run it from a system with fonts-dejavu-core installed (or the still-bundled
fonts, as at generation time). Requires fontTools.
"""
import sys
import os

FONTS = [
    ("DejaVuSans.ttf", "SANS"),
    ("DejaVuSans-Bold.ttf", "SANS_BOLD"),
    ("DejaVuSerif.ttf", "SERIF"),
    ("DejaVuSerif-Bold.ttf", "SERIF_BOLD"),
]


def main() -> int:
    if len(sys.argv) != 2:
        print("usage: gen_font_table.py <fonts dir>", file=sys.stderr)
        return 2
    from fontTools.ttLib import TTFont

    fonts_dir = sys.argv[1]
    out = sys.stdout
    out.write("//! AUTO-GENERATED by scripts/gen_font_table.py — DO NOT EDIT.\n")
    out.write("//! Source fonts: DejaVu (fonts-dejavu, Bitstream Vera-derived;\n")
    out.write("//! free license, redistribution + embedding permitted).\n")
    out.write("//! One sorted (codepoint, advance-in-font-units) table per face,\n")
    out.write("//! replacing the embedded TTFs + ttf-parser with identical widths:\n")
    out.write("//! `adv / units_per_em * size` is exactly what the parser computed.\n\n")

    for fname, tag in FONTS:
        path = os.path.join(fonts_dir, fname)
        font = TTFont(path, lazy=True)
        upem = font["head"].unitsPerEm
        cmap = font.getBestCmap()
        hmtx = font["hmtx"]
        glyphOrder = font.getGlyphOrder()
        entries = []
        for cp in cmap:
            if cp > 0x10FFFF or not (0 <= cp):
                continue
            gname = cmap[cp]
            try:
                adv = hmtx[gname][0]
            except Exception:
                continue
            if adv is None:
                continue
            entries.append((cp, adv))
        entries.sort()
        # sanity: cmap entries are unique codepoints
        assert len({e[0] for e in entries}) == len(entries)
        out.write(f"/// {fname}: {len(entries)} cmap entries, units_per_em = {upem}.\n")
        out.write(f"pub const {tag}_UPEM: u32 = {upem};\n")
        out.write(f"pub const {tag}_ADV: &[(u32, u16)] = &[\n")
        for cp, adv in entries:
            out.write(f"    (0x{cp:04X}, {adv}),\n")
        out.write("];\n\n")
        print(f"{fname}: {len(entries)} entries, upem {upem}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
